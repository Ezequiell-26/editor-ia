import { z } from 'zod';

/**
 * Small shared primitives of the project format. Each one is a wire contract:
 * the same value must validate in TypeScript and in the Rust boundary, so the
 * rules stay textual and bounded rather than language specific.
 */

const UUID_V4 = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

/**
 * Entity ids are uuid v4 and are only ever produced by the application or by a
 * validated AI operation. Slugs are rejected on purpose: a hand typed id is
 * the usual way a reference breaks in a project file.
 */
export const EntityIdSchema = z
  .string()
  .regex(UUID_V4, 'entity ids must be uuid v4 generated by the application');

export const Sha256Schema = z
  .string()
  .regex(/^[0-9a-f]{64}$/, 'integrity digests must be 64 lower case hex characters');

export const IsoDateTimeSchema = z.string().datetime({ offset: true });

export const LanguageTagSchema = z
  .string()
  .regex(/^[a-z]{2,3}(-[a-z0-9]{2,8})*$/i, 'captions must use a BCP 47 language subtag');

export const UnitIntervalSchema = z.number().min(0).max(1);

export const DecibelSchema = z.number().gte(-60).lte(12);

export type JsonValue =
  | string
  | number
  | boolean
  | null
  | JsonValue[]
  | { [key: string]: JsonValue };

function isPlainJsonContainer(value: unknown): boolean {
  if (Array.isArray(value)) {
    return true;
  }
  if (typeof value !== 'object' || value === null) {
    return false;
  }
  const prototype = Object.getPrototypeOf(value);
  return prototype === Object.prototype || prototype === null;
}

function collectJsonViolations(value: unknown, path: string[], out: string[]): void {
  if (value === null || typeof value === 'string' || typeof value === 'boolean') {
    return;
  }
  if (typeof value === 'number') {
    if (!Number.isFinite(value) || Math.abs(value) > Number.MAX_SAFE_INTEGER) {
      out.push(path.join('.'));
    }
    return;
  }
  if (typeof value === 'bigint') {
    out.push(path.join('.'));
    return;
  }
  if (!isPlainJsonContainer(value)) {
    out.push(path.join('.'));
    return;
  }
  const entries = Object.entries(value as Record<string, unknown>);
  for (const [key, child] of entries) {
    collectJsonViolations(child, [...path, key], out);
  }
}

/**
 * Any value that survives `JSON.stringify` unchanged. Functions, symbols,
 * `undefined`, dates, bigints, non finite numbers and non plain objects are
 * refused because a project file must round-trip through Rust, TypeScript and
 * the render worker without a silent change of representation.
 *
 * The check walks the raw input instead of a parsed union: a `Date` parses as
 * an empty record and would otherwise be accepted with its data quietly lost.
 */
export const JsonValueSchema: z.ZodType<JsonValue> = z
  .unknown()
  .superRefine((value, ctx) => {
    const violations: string[] = [];
    collectJsonViolations(value, [], violations);
    if (violations.length > 0) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        path: [violations[0] ?? ''],
        message: 'only JSON serializable values may be stored in a project file',
      });
    }
  })
  .transform((value) => value as JsonValue) as unknown as z.ZodType<JsonValue>;

export type EntityId = z.infer<typeof EntityIdSchema>;
